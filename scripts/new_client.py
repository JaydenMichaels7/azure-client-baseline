#!/usr/bin/env python3
"""Generate a new client environment folder from the dev template.

    python scripts/new_client.py globex                # creates environments/globex-dev
    python scripts/new_client.py globex --env prod --location uksouth
    python scripts/new_client.py globex --dry-run      # show what would happen

It copies environments/dev, sets the client name, environment and state key, and writes an
ONBOARDING.md checklist next to the new files. It deliberately does NOT touch bootstrap/
or the workflow: identity and pipeline changes are reviewed by a person in a pull request.
"""
from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_TEMPLATE = REPO_ROOT / "environments" / "dev"
IGNORE = shutil.ignore_patterns(
    ".terraform", "*.tfstate", "*.tfstate.*", "tfplan", "*.tfplan", "terraform.tfvars", "ONBOARDING.md"
)
CLIENT_RE = re.compile(r"^[a-z][a-z0-9]{1,7}$")  # 2-8 chars, so name_prefix stays <= 15
ENV_RE = re.compile(r"^[a-z][a-z0-9]{1,5}$")


def validate(client, env):
    if not CLIENT_RE.match(client):
        raise ValueError("client must be 2-8 characters: lowercase letters and digits, starting with a letter")
    if not ENV_RE.match(env):
        raise ValueError("env must be 2-6 characters: lowercase letters and digits, starting with a letter")
    if len(f"{client}-{env}") > 15:
        raise ValueError("client and env together are too long (Key Vault names max out at 24 characters)")


def set_variable_default(text, variable, value):
    """Replace the default of one Terraform variable block."""
    pattern = re.compile(
        r'(variable\s+"%s"\s*\{.*?\bdefault\s*=\s*)"[^"]*"' % re.escape(variable), re.DOTALL
    )
    new_text, count = pattern.subn(lambda m: m.group(1) + f'"{value}"', text, count=1)
    if count != 1:
        raise ValueError(f"could not find a default for variable {variable!r}")
    return new_text


def set_state_key(text, key):
    new_text, count = re.subn(r'(\bkey\s*=\s*)"[^"]*"', lambda m: m.group(1) + f'"{key}"', text, count=1)
    if count != 1:
        raise ValueError("could not find the state key in backend.tf")
    return new_text


def onboarding_text(name, client, env):
    label = name.replace("-", "_")
    return f"""# Onboarding checklist: {name}

Generated by `scripts/new_client.py` from `environments/dev`. Review this folder in a pull request.

What was set for you
- Client `{client}`, environment `{env}` -> resource group `rg-{name}`
- Terraform state key `{name}.terraform.tfstate` in the existing state container
- The VM stays disabled (`enable_compute = false`) until you decide otherwise

What still needs a person

1. **Identity.** Add this credential to `bootstrap/main.tf`, then run `terraform apply` in `bootstrap/` locally:

```hcl
resource "azuread_application_federated_identity_credential" "env_{label}" {{
  #checkov:skip=CKV_AZURE_249:Subject is pinned to one repo; environment restricted to the main branch
  application_id = azuread_application.github.id
  display_name   = "github-env-{name}"
  audiences      = ["api://AzureADTokenExchange"]
  issuer         = "https://token.actions.githubusercontent.com"
  subject        = "repo:${{var.github_org}}@${{var.github_owner_id}}/${{var.github_repo}}@${{var.github_repo_id}}:environment:{name}"
}}
```

2. **GitHub Environment.** Settings -> Environments -> New environment named `{name}`, then restrict deployment branches to `main`.

3. **Pipeline.** `.github/workflows/terraform.yml` currently targets `environments/dev` only (`TF_DIR` and `environment: dev`). Add plan and apply jobs for `{name}`, or convert the jobs to a matrix.

4. **Pull request.** Open a PR, read the plan (a new environment should only add resources), merge, and watch the apply.

Note: every client gets its own VNet using the default address space. If clients will ever be peered, give each a unique range first.
"""


def generate(client, env, template=DEFAULT_TEMPLATE, location=None, dest_root=None, dry_run=False):
    validate(client, env)
    template = Path(template)
    dest_root = Path(dest_root) if dest_root else template.parent
    name = f"{client}-{env}"
    target = dest_root / name

    if not template.is_dir():
        raise FileNotFoundError(f"template folder not found: {template}")
    if target.exists():
        raise FileExistsError(f"{target} already exists; refusing to overwrite it")
    if dry_run:
        return target

    shutil.copytree(template, target, ignore=IGNORE)

    variables = target / "variables.tf"
    text = variables.read_text(encoding="utf-8")
    text = set_variable_default(text, "client_name", client)
    text = set_variable_default(text, "environment", env)
    if location:
        text = set_variable_default(text, "location", location)
    variables.write_text(text, encoding="utf-8")

    backend = target / "backend.tf"
    backend.write_text(
        set_state_key(backend.read_text(encoding="utf-8"), f"{name}.terraform.tfstate"), encoding="utf-8"
    )

    (target / "ONBOARDING.md").write_text(onboarding_text(name, client, env), encoding="utf-8")
    return target


def main(argv=None):
    p = argparse.ArgumentParser(description="Create a new client environment from the dev template.")
    p.add_argument("client", help="short client name, e.g. globex")
    p.add_argument("--env", default="dev", help="environment name (default: dev)")
    p.add_argument("--location", help="Azure region to set as the default (default: keep the template's)")
    p.add_argument("--template", default=str(DEFAULT_TEMPLATE), help="folder to copy from")
    p.add_argument("--dry-run", action="store_true", help="show what would be created, write nothing")
    args = p.parse_args(argv)

    try:
        target = generate(args.client, args.env, args.template, args.location, dry_run=args.dry_run)
    except (ValueError, FileExistsError, FileNotFoundError) as err:
        print(f"error: {err}", file=sys.stderr)
        return 2

    if args.dry_run:
        print(f"[dry run] would create {target}")
        return 0
    print(f"Created {target}")
    print(f"Next: read {target / 'ONBOARDING.md'} and open a pull request. Nothing has been deployed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
